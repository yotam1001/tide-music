"""Read-only YouTube Music bridge. Credentials arrive on stdin, never argv."""
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile
import time
from urllib.parse import urlsplit
import warnings

MAX_INPUT = 65536
MAX_TRACKS = 2000
LOGIN_SECONDS = 8 * 60
MUSIC_URL = "https://music.youtube.com"
SESSION_HEADERS = {
    "accept": 1024, "accept-language": 1024, "content-type": 256,
    "user-agent": 1024, "x-goog-authuser": 8, "x-goog-pageid": 128,
    "cookie": 32768,
}
warnings.filterwarnings("ignore")


def music_url(value, browse=False):
    """Accept only the official HTTPS host, never lookalikes or other Google URLs."""
    try:
        url = urlsplit(value)
        return (url.scheme == "https" and url.hostname == "music.youtube.com"
                and url.port in (None, 443) and not url.username and not url.password
                and (not browse or url.path == "/youtubei/v1/browse"))
    except (TypeError, ValueError):
        return False


def safe_header(value, limit):
    return (isinstance(value, str) and bool(value) and len(value) <= limit
            and all(32 <= ord(char) < 127 or char == "\t" for char in value))


def music_cookies(cookies):
    """Input must come from context.cookies(MUSIC_URL); also enforce its domain."""
    result = []
    for cookie in cookies[:200]:
        if cookie.get("domain") not in (".youtube.com", "youtube.com", "music.youtube.com",
                                        ".music.youtube.com"):
            continue
        if cookie.get("path", "/") != "/":
            continue
        name, value = cookie.get("name", ""), cookie.get("value", "")
        if (re.fullmatch(r"[A-Za-z0-9_-]{1,128}", name)
                and safe_header(value, 4096) and ";" not in value):
            result.append(name + "=" + value)
    value = "; ".join(result)
    return value if len(value) <= SESSION_HEADERS["cookie"] else ""


def session_headers(raw, cookies=()):
    """Keep only YTMusic inputs; transient Authorization is generated by ytmusicapi."""
    headers = {}
    for name, value in raw.items():
        key = name.lower()
        if key in SESSION_HEADERS and safe_header(value, SESSION_HEADERS[key]):
            headers[key] = value
    if not headers.get("cookie"):
        headers["cookie"] = music_cookies(cookies)
    authuser = headers.get("x-goog-authuser", "")
    if not re.fullmatch(r"[0-9]{1,4}", authuser):
        return None
    cookie_values = dict(part.strip().split("=", 1) for part in headers["cookie"].split(";")
                         if "=" in part)
    if not cookie_values.get("__Secure-3PAPISID"):
        return None
    if "x-goog-pageid" in headers and not re.fullmatch(r"[0-9]{1,128}", headers["x-goog-pageid"]):
        return None
    headers["origin"] = MUSIC_URL
    return headers


def authenticated_request(request):
    if not music_url(request.url, browse=True) or request.method != "POST":
        return False
    # Request.headers omits cookies. Only request all_headers after the browser
    # itself has sent an authenticated Music browse request, never during sign-in.
    headers = request.headers
    return (bool(re.fullmatch(r"[0-9]{1,4}", headers.get("x-goog-authuser", "")))
            and bool(re.search(r"(?:^| )SAPISID(?:1P|3P)?HASH ",
                               headers.get("authorization", ""))))


def remove_login_profile(profile, directory):
    # Resolve immediately before every recursive delete. Never remove the account
    # directory, an old browser profile, or a path outside our private directory.
    for _ in range(20):
        resolved = profile.resolve()
        if resolved.parent != directory.resolve() or not resolved.name.startswith("edge-login-"):
            return False
        try:
            shutil.rmtree(resolved)
            return True
        except FileNotFoundError:
            return True
        except OSError:
            time.sleep(0.25)
    return False


def wait_for_login(context, timeout=LOGIN_SECONDS, start_page=None):
    candidate = None
    closed = False

    def did_close(_context):
        nonlocal closed
        closed = True

    def observed(response):
        nonlocal candidate
        try:
            request = response.request
            if response.status == 200 and authenticated_request(request):
                candidate = request.all_headers()
        except Exception:
            # Browser-close races and network errors must never expose headers.
            pass

    context.on("response", observed)
    context.on("close", did_close)
    if start_page is not None:
        start_page.goto(MUSIC_URL, wait_until="domcontentloaded", timeout=30000)
    deadline = time.monotonic() + min(max(timeout, 0), LOGIN_SECONDS)
    while time.monotonic() < deadline:
        if closed:
            return {"type": "error", "code": "login_closed"}
        pages = [page for page in context.pages if not page.is_closed()]
        if not pages:
            return {"type": "error", "code": "login_closed"}
        for page in pages:
            url = urlsplit(page.url)
            if url.hostname == "accounts.google.com" and "/signin/rejected" in url.path:
                return {"type": "error", "code": "login_blocked"}
        if candidate and any(music_url(page.url) for page in pages):
            headers = session_headers(candidate, context.cookies(MUSIC_URL))
            if headers:
                return {"type": "session", "headers": headers}
        # Playwright waits dispatch browser events while the user operates Edge.
        try:
            pages[0].wait_for_timeout(250)
        except Exception:
            if closed or not context.pages:
                return {"type": "error", "code": "login_closed"}
            raise
    return {"type": "error", "code": "login_timeout"}


def connect(directory):
    from playwright.sync_api import sync_playwright
    directory = Path(directory).resolve(strict=True)
    if not directory.is_dir():
        raise ValueError("invalid private directory")
    profile = Path(tempfile.mkdtemp(prefix="edge-login-", dir=directory))
    result = {"type": "error", "code": "login_browser"}
    # Debugging switches can make the Playwright driver log protocol credentials.
    suppressed = {name: os.environ.pop(name) for name in (
        "DEBUG", "PWDEBUG", "SELENIUM_REMOTE_URL", "SELENIUM_REMOTE_CAPABILITIES",
        "SELENIUM_REMOTE_HEADERS") if name in os.environ}
    try:
        with sync_playwright() as playwright:
            context = None
            try:
                context = playwright.chromium.launch_persistent_context(
                    str(profile), channel="msedge", headless=False, timeout=30000,
                    accept_downloads=False, chromium_sandbox=True,
                )
                page = context.pages[0] if context.pages else context.new_page()
                result = wait_for_login(context, start_page=page)
            finally:
                if context is not None:
                    context.close()
    except Exception:
        pass
    finally:
        os.environ.update(suppressed)
        if not remove_login_profile(profile, directory):
            result = {"type": "error", "code": "cleanup"}
    return result


def clean(value, limit=300):
    return "".join(c for c in str(value or "") if c.isprintable())[:limit]


def identifier(value, video=False):
    value = str(value or "")
    pattern = r"[A-Za-z0-9_-]{11}" if video else r"[A-Za-z0-9_-]{1,160}"
    return value if re.fullmatch(pattern, value) else ""


def tracks(items):
    result = []
    for item in items[:MAX_TRACKS]:
        video = identifier(item.get("videoId"), True)
        if not video:
            continue
        album = item.get("album") or {}
        result.append({
            "title": clean(item.get("title")),
            "artist": clean(", ".join(a.get("name", "") for a in item.get("artists", []) or [])),
            "album": clean(album.get("name") if isinstance(album, dict) else ""),
            "source": "https://www.youtube.com/watch?v=" + video,
        })
    return result


def run(client, request):
    action = request["action"]
    if action == "library":
        info = client.get_account_info()
        playlists = client.get_library_playlists(limit=201)
        return {"type": "library", "account": clean(info.get("accountName") or info.get("name") or "YouTube Music"),
                "playlists": [{"id": identifier(p.get("playlistId")), "title": clean(p.get("title")),
                               "subtitle": clean(str(p.get("count") or "") + " tracks")}
                              for p in playlists[:200] if identifier(p.get("playlistId"))],
                "truncated": len(playlists) > 200}
    if action in ("playlist", "liked"):
        if action == "playlist":
            playlist = identifier(request.get("id"))
            if not playlist:
                raise ValueError("invalid identifier")
            data = client.get_playlist(playlist, limit=MAX_TRACKS + 1)
        else:
            data = client.get_liked_songs(limit=MAX_TRACKS + 1)
        items = data.get("tracks", [])
        return {"type": "tracks", "tracks": tracks(items), "truncated": len(items) > MAX_TRACKS}
    if action == "home":
        shelves = client.get_home(limit=3)
        cards = []
        for shelf in shelves[:3]:
            for item in shelf.get("contents", [])[:40]:
                kind = clean(item.get("type") or "unknown", 30)
                video = identifier(item.get("videoId"), True)
                playlist = identifier(item.get("playlistId"))
                if video:
                    kind, item_id = "song", video
                elif playlist and kind not in ("album", "artist"):
                    kind, item_id = "playlist", playlist
                else:
                    item_id = identifier(item.get("browseId"))
                cards.append({"id": item_id, "title": clean(item.get("title")),
                              "subtitle": clean(", ".join(a.get("name", "") for a in item.get("artists", []) or [])),
                              "kind": kind, "shelf": clean(shelf.get("title"))})
        return {"type": "home", "cards": cards}
    raise ValueError("unsupported action")


def main():
    try:
        raw = sys.stdin.buffer.read(MAX_INPUT + 1)
        if len(raw) > MAX_INPUT:
            raise ValueError("input limit")
        request = json.loads(raw)
        if request.get("action") == "connect":
            result = connect(request["directory"])
            print(json.dumps(result, ensure_ascii=True))
            return
        from ytmusicapi import YTMusic
        from ytmusicapi.helpers import initialize_headers
        import requests
        from functools import partial
        session = requests.Session()
        session.request = partial(session.request, timeout=20)
        headers = initialize_headers()
        headers.update(request.pop("headers"))
        client = YTMusic(auth=headers, user=headers.get("x-goog-pageid"), requests_session=session)
        result = run(client, request)
        print(json.dumps(result, ensure_ascii=True))
    except ImportError:
        print('{"type":"error","code":"runtime"}')
    except Exception:
        # Exceptions can include HTTP headers or request data: never serialize them.
        print('{"type":"error","code":"request"}')


if __name__ == "__main__":
    main()
